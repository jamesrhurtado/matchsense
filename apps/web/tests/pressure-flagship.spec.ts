import {test,expect} from '@playwright/test';
const headers={'X-Producer-Token':'local-demo-producer'};
test('pressure flagship: review, source evidence, approval, audience lenses, Spanish focus, mobile and recap',async({page,request,context},info)=>{
 test.setTimeout(45000);
 const catalogue=await(await request.get('/api/matches')).json();
 const enabled=catalogue.matches.some((m:{match_id:string})=>m.match_id==='match-0c0a000000000005');
 if(process.env.WHY_NOW_MATCH_COVERAGE_E2E==='1')expect(enabled).toBeTruthy();
 test.skip(!enabled,'Pressure flagship catalogue is opt-in.');
 const created=await(await request.post('/api/replay-sessions',{headers,data:{match_id:'match-0c0a000000000005'}})).json();
 const base=`/api/replay-sessions/${created.session_id}`;
 await request.post(base+'/control',{headers,data:{action:'seek',clock_ms:92000}});
 const before=await(await request.get(base+'/snapshot')).json();expect(before.stories).toHaveLength(0);
 await page.addInitScript(()=>sessionStorage.setItem('why-now-token','local-demo-producer'));
 await page.goto(`/studio/${created.session_id}`);
 const queue=page.getByRole('group',{name:'Suggested insights'});
 await queue.getByLabel('Event family').selectOption('pressure');
 await queue.getByRole('button',{name:/01:31.*Nearby pressure change/}).click();
 await expect(page.getByRole('region',{name:'Why this moment'})).toContainText('previous three');
 await page.getByRole('button',{name:'Review evidence',exact:true}).click();
 const evidence=page.getByTestId('pressure-evidence').first();
 await expect(evidence).toContainText('2.0');await expect(evidence).toContainText('0.4');await expect(evidence).toContainText('30.0 m');
 await expect(evidence.getByRole('table')).toContainText('25.0 m');
 await expect(evidence).toContainText('before 100% (2.0 of 2.0 s); after 100% (2.0 of 2.0 s)');
 await page.getByRole('button',{name:'Approve for viewers',exact:true}).click();
 const viewer=await context.newPage();await viewer.setViewportSize({width:390,height:844});
 await viewer.goto(`/watch/${created.session_id}`);
 await expect(viewer.getByTestId('audience-explanation')).toContainText('30.0 m forward');
 await expect(viewer.getByRole('region',{name:'Why this moment'})).toContainText('2.0 to 0.4');
 await viewer.getByRole('button',{name:'Check the evidence',exact:true}).click();
 await expect(viewer.getByTestId('pressure-evidence').last()).toBeVisible();
 await viewer.getByText('Compare audience views',{exact:true}).last().click();
 await expect(viewer.getByRole('heading',{name:'For the casual viewer'}).last()).toBeVisible();
 await expect(viewer.getByRole('heading',{name:'For the analyst'}).last()).toBeVisible();
 expect(await viewer.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await viewer.screenshot({path:info.outputPath('pressure-mobile.png'),fullPage:true});
 await viewer.getByLabel('Language',{exact:true}).selectOption('es');
 await expect(viewer.getByTestId('audience-explanation')).toContainText('pasó 30.0 m');
 await viewer.getByLabel('Seguir equipo o jugador').selectOption('blue-09');
 await expect(viewer.getByTestId('audience-explanation')).toContainText('Beni Vidal');
 await viewer.getByLabel('Seguir equipo o jugador').selectOption('blue-01');
 await expect(viewer.getByText('No hay historias aprobadas que involucren esta selección en este intervalo.')).toBeVisible();
 await viewer.getByLabel('Seguir equipo o jugador').selectOption('');
 await expect(viewer.getByTestId('audience-explanation')).toContainText('pasó 30.0 m');
 await viewer.getByRole('button',{name:'Ponerme al día'}).click();
 await expect(viewer.getByRole('heading',{name:'Resumen del segmento'})).toBeVisible();
 await expect(viewer.getByRole('heading',{name:'Cambio de presión cercana',level:3,exact:true})).toBeVisible();
 await viewer.getByRole('button',{name:'Cerrar resumen'}).click();
 await viewer.setViewportSize({width:1366,height:900});
 await viewer.getByLabel('Idioma',{exact:true}).selectOption('en');
 await expect(viewer.getByTestId('audience-explanation')).toContainText('30.0 m forward');
 await viewer.screenshot({path:info.outputPath('pressure-desktop.png'),fullPage:true});
 expect((await(await request.get(base+'/snapshot')).json()).overlay_story_id).toBe('story-pressure-pass-4');
});
