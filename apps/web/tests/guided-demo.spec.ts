import {test,expect} from '@playwright/test';
const headers={'X-Producer-Token':'local-demo-producer'};
test('moving demo pauses for review, reveals evidence in view, and can play continuously',async({page,request})=>{
 test.setTimeout(90000);
 const catalog=await(await request.get('/api/matches')).json();
 const enabled=catalog.matches.some((m:{match_id:string})=>m.match_id==='match-0c0a000000000003');
 if(process.env.WHY_NOW_MATCH_COVERAGE_E2E==='1')expect(enabled).toBeTruthy();
 test.skip(!enabled,'Versioned guided demo requires match coverage.');
 const created=await(await request.post('/api/replay-sessions',{headers,data:{match_id:'match-0c0a000000000003'}})).json();
 const base=`/api/replay-sessions/${created.session_id}`;
 await page.addInitScript(()=>sessionStorage.setItem('why-now-token','local-demo-producer'));
 await page.goto(`/studio/${created.session_id}`);
 await expect(page.getByLabel('Pause at new event types')).toBeChecked();
 const player=page.locator('[data-player-id="blue-02"] text');
 await expect(player).toBeVisible();const start=await player.getAttribute('x');
 await page.getByRole('button',{name:'Play',exact:true}).click();
 await expect.poll(()=>player.getAttribute('x')).not.toBe(start);
 await expect(page.getByText('Paused for review: pass.',{exact:false})).toBeVisible({timeout:30000});
 await expect(page.getByRole('button',{name:'Play',exact:true})).toBeVisible();
 const snap=await(await request.get(base+'/snapshot',{headers})).json();
 expect(snap.running).toBeFalsy();expect(snap.clock_ms).toBeGreaterThanOrEqual(16200);expect(snap.clock_ms).toBeLessThan(25000);
 await page.getByRole('button',{name:'Show why',exact:true}).click();
 const evidence=page.getByLabel('Evidence for the selected moment',{exact:true});
 await expect(evidence).toBeInViewport();await expect(evidence).toBeFocused();
 await page.getByRole('button',{name:'Approve',exact:true}).click();
 const publicSnap=await(await request.get(base+'/snapshot')).json();expect(publicSnap.overlay).toBeTruthy();
 await page.getByLabel('Pause at new event types').uncheck();
 if(!(await page.getByLabel('Skip to time (seconds)').isVisible()))await page.getByText('Replay navigation',{exact:true}).click();await page.getByLabel('Skip to time (seconds)').fill('28');await page.getByRole('button',{name:'Skip forward',exact:true}).click();
 await page.getByLabel('Replay speed').selectOption('4');await page.getByRole('button',{name:'Play',exact:true}).click();
 await expect.poll(async()=>{const s=await(await request.get(base+'/snapshot',{headers})).json();return s.clock_ms;}).toBeGreaterThan(35000);
 await expect(page.getByRole('button',{name:'Pause',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.getByText('Replay data details',{exact:true}).click();
 await expect(page.getByText('These are position samples and source records, not a count of football incidents.',{exact:false})).toBeVisible();
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
